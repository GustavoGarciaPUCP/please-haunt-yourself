import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
await mkdir('output/playwright', { recursive: true });
const url = new URL('/haunt.html', process.env.HAUNT_BASE_URL ?? 'http://127.0.0.1:5174').href;
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const outcomes = [], errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 980 }, reducedMotion: 'no-preference' });
  await page.addInitScript(() => localStorage.setItem('haunt.guide.v1', 'dismissed'));
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(url);
  const terminal = page.locator('.terminal-console');
  const input = terminal.getByRole('textbox', { name: 'Game console command' });
  const transcript = terminal.locator('.console-output');
  const scene = page.locator('.echo-scene-container');
  const action = name => scene.locator(`[data-action="${name}"]`);
  const command = async value => {
    await page.locator('#btn-terminal').click();
    await input.fill(value);
    await input.press('Enter');
  };
  const state = value => page.waitForFunction(expected => document.querySelector('.echo-scene-container')?.dataset.state === expected, value);
  assert.ok(await input.evaluate(el => document.activeElement === el));
  assert.match(await input.evaluate(el => getComputedStyle(el).fontFamily), /Cascadia|Consolas/);
  assert.match(await terminal.locator('.console-caret').evaluate(el => getComputedStyle(el).animationName), /console-blink/);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await terminal.locator('.console-caret').evaluate(el => getComputedStyle(el).animationName), 'none');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await command('ps');
  assert.match(await transcript.textContent(), /PID\s+PPID\s+STATE/);
  await command('inspect mirror');
  assert.match(await transcript.textContent(), /KILL leaves my last frame/);
  await input.press('ArrowUp');
  assert.equal(await input.inputValue(), 'inspect mirror');
  await input.press('ArrowDown');
  assert.equal(await input.inputValue(), '');
  await page.locator('#btn-echo').click();
  await state('editing');
  await page.waitForTimeout(300);
  await page.screenshot({ path: 'output/playwright/app-identities-desktop.png' });
  outcomes.push('native-looking shell: actual text input, process table, history and reduced-motion cursor');

  await command('kill -TERM 410');
  assert.match(await transcript.textContent(), /restarted mirror.watch as \[411\]/);
  assert.equal(await scene.getAttribute('data-frame'), 'live');
  assert.match(await scene.locator('.echo-feed-state').textContent(), /\[411\]/);
  await command('kill -TERM 410');
  assert.match(await transcript.textContent(), /No live signal target 410/);
  await command('kill -TERM 400');
  await command('kill -TERM 411');
  assert.equal(await scene.getAttribute('data-frame'), 'released');
  assert.equal(await scene.locator('.private-footage').evaluate(el => getComputedStyle(el).opacity), '0');
  assert.match(await scene.locator('[data-private]').textContent(), /feed released/);
  await page.locator('#btn-echo').click();
  await action('rehearse').click();
  await state('complete');
  assert.equal(await scene.locator('.farewell-prop').evaluate(el => Math.round(parseFloat(el.style.top) * 4.1)), 240);
  await page.screenshot({ path: 'output/playwright/process-clean-release.png' });
  outcomes.push('supervisor respawns a new PID; stopping supervisor then child releases feed and permits an uncovered entrance');

  await command('restore mirror');
  await command('kill 400');
  await command('kill -9 412');
  assert.equal(await scene.getAttribute('data-frame'), 'afterimage');
  await page.locator('#btn-echo').click();
  await action('rehearse').click();
  await state('failed');
  assert.match(await scene.locator('.echo-status').textContent(), /afterimage/);
  await page.screenshot({ path: 'output/playwright/process-afterimage.png' });
  await action('edit').click();
  await action('help').click();
  await action('align').click();
  await action('help').click();
  await action('rehearse').click();
  await state('complete');
  outcomes.push('forced exit leaves an actual afterimage; coverage remains a valid alternative recovery');

  await action('edit').click();
  await input.fill('restore mirror');
  await action('rehearse').click();
  await state('performing');
  await input.press('Enter');
  await state('editing');
  await page.waitForTimeout(800);
  assert.equal(await scene.getAttribute('data-state'), 'editing');
  assert.match(await scene.locator('.echo-status').textContent(), /Console changed the set/);
  await page.locator('#btn-echo').click();
  await action('leave').click();
  await command('restore mirror');
  assert.equal(await scene.getAttribute('data-state'), 'left');
  await page.waitForTimeout(750);
  assert.equal(await scene.getAttribute('data-state'), 'left');
  outcomes.push('console edits cancel active cues and require rehearsal; a departed visit stays departed');

  await command('help');
  await terminal.locator('input').press('Control+l');
  assert.equal(await transcript.textContent(), '');
  await command('<script>window.testInjection=true</script>');
  assert.equal(await page.evaluate(() => window.testInjection), undefined);
  assert.equal(await transcript.locator('script').count(), 0);
  await command('ps');
  await page.locator('#window-terminal [aria-label="Close"]').click();
  await page.locator('#window-terminal').waitFor({ state: 'detached' });
  await page.locator('#btn-terminal').click();
  await command('ps');
  assert.match((await transcript.locator('.console-line').allTextContents()).join('\n'), /^414\s+400\s+observing\s+mirror.watch/m);
  assert.match(await terminal.locator('.console-process-state').textContent(), /live/);
  outcomes.push('clear/errors do not execute code; closing and reopening a console preserves the shared page session');

  await page.setViewportSize({ width: 390, height: 844 });
  await command('ps');
  assert.ok(await input.isVisible());
  assert.equal(await terminal.evaluate(el => el.scrollWidth <= el.clientWidth + 1), true);
  await page.screenshot({ path: 'output/playwright/terminal-mobile.png' });
  await page.setViewportSize({ width: 800, height: 450 });
  await command('inspect mirror');
  const runBounds = await terminal.getByRole('button', { name: 'Run', exact: true }).boundingBox();
  assert.ok(runBounds.y >= 0 && runBounds.y + runBounds.height <= 390);
  outcomes.push('console input, transcript and Run remain usable at 390x844 and 800x450');
  assert.deepEqual(errors, []);
  const report = { url, passed: outcomes.length, outcomes, pageErrors: errors, limitations: ['Local fictional services; no host process control.', 'Human enjoyment and competitive originality not established by these checks.'] };
  await writeFile('output/playwright/process-console-results.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} catch (error) { console.error(error); process.exitCode = 1; }
finally { await browser.close(); }
