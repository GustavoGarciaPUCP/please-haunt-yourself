import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
await mkdir('output/playwright', { recursive: true });
const url = new URL('/haunt.html', process.env.HAUNT_BASE_URL ?? 'http://127.0.0.1:5174').href;
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const outcomes = [], errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 980 } });
  await page.addInitScript(() => localStorage.setItem('haunt.guide.v2', 'dismissed'));
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(url);
  const terminal = page.locator('.terminal-console');
  const shell = terminal.locator('.terminal-shell-view');
  const interior = terminal.locator('.legacy-interior');
  const input = terminal.locator('input[name="command"]');
  const output = terminal.locator('.console-output');
  const cmd = async value => { await input.fill(value); await input.press('Enter'); };
  const action = name => interior.locator(`[data-legacy="${name}"]`);
  const health = expected => page.waitForFunction(value => document.querySelector('.terminal-console')?.dataset.terminalHealth === value, expected);
  await health('haunted');
  await cmd('echo hello');
  assert.match(await output.textContent(), /MARA@1987/);
  await terminal.locator('[data-ask-status]').click();
  assert.match(await output.textContent(), /Not yet/);
  const hauntedBackground = await page.locator('#window-terminal').evaluate(el => getComputedStyle(el).backgroundColor);
  await page.screenshot({ path: 'output/playwright/terminal-haunted.png' });
  await page.locator('#window-terminal').evaluate(el => el.dataset.instanceProbe = 'same-app');
  await cmd('enter last.session');
  await interior.waitFor({ state: 'visible' });
  assert.equal(await shell.isVisible(), false);
  assert.equal(await page.locator('.window').count(), 1);
  for (let i = 0; i < 3; i++) await action('step').click();
  assert.match(await interior.locator('.legacy-execution').textContent(), /3088.*cycles 1/);
  await interior.locator('[data-link="output"]').click();
  await action('return').click();
  await terminal.locator('[data-ask-status]').click();
  assert.match(await output.textContent(), /silenced its speaker/);
  await health('haunted');
  outcomes.push('the same app enters its own trace; stepping shows revival, and silence does not count as recovery');

  await terminal.locator('[data-enter-session]').click();
  await interior.locator('[data-link="restart"]').click();
  await page.screenshot({ path: 'output/playwright/terminal-session-interior.png' });
  await action('term').click();
  await health('remembered');
  await action('return').click();
  await terminal.locator('[data-ask-status]').click();
  assert.match(await output.textContent(), /do not have to repeat/);
  await page.screenshot({ path: 'output/playwright/terminal-check-in.png' });
  await cmd('clear'); await cmd('echo this prompt is mine');
  assert.doesNotMatch(await output.textContent(), /MARA@1987/);
  assert.match(await output.textContent(), /this prompt is mine/);
  await cmd('cat last-session');
  assert.match(await output.textContent(), /no longer executable/);
  assert.notEqual(await page.locator('#window-terminal').evaluate(el => getComputedStyle(el).backgroundColor), hauntedBackground);
  assert.equal(await page.locator('#window-terminal').getAttribute('data-instance-probe'), 'same-app');
  assert.match(await page.locator('.desktop-task').textContent(), /TERMINAL recovered/);
  await page.screenshot({ path: 'output/playwright/terminal-recovered.png' });
  outcomes.push('clean exit repairs actual echo behavior, preserves the chosen archive, changes the shell and answers a real check-in');

  await page.locator('#window-terminal [aria-label="Close"]').click();
  await page.locator('#window-terminal').waitFor({ state: 'detached' });
  await page.locator('#btn-terminal').click();
  await health('remembered');
  await terminal.locator('[data-ask-status]').click();
  assert.match(await output.textContent(), /remember her line/);
  await cmd('restore terminal');
  await terminal.locator('[data-enter-session]').click();
  await interior.locator('[data-link="archive"]').click();
  await action('term').click();
  await health('haunted');
  await interior.locator('[data-link="restart"]').click();
  await action('term').click();
  await health('blank');
  await action('return').click();
  await terminal.locator('[data-ask-status]').click();
  assert.match(await output.textContent(), /cannot remember the line/);
  await cmd('cat last-session');
  assert.match(await output.textContent(), /archive is blank/);
  outcomes.push('repair survives app reopen; erasing memory alone fails, while a clean blank-archive ending has a different acknowledgement');

  await cmd('restore terminal');
  await terminal.locator('[data-enter-session]').click();
  await interior.locator('[data-link="restart"]').click();
  await action('kill').click();
  await health('residue');
  assert.equal(await action('resume').isVisible(), true);
  await action('resume').click();
  await action('term').click();
  await health('remembered');
  await action('undo').click();
  await health('haunted');
  await action('return').click();
  await terminal.locator('[data-ask-status]').click();
  assert.match(await output.textContent(), /Not yet/);
  outcomes.push('forced-stop residue is not awarded recovery; resume/clean-exit and Undo preserve meaningful state');

  for (const viewport of [{ width: 390, height: 844 }, { width: 800, height: 450 }]) {
    await page.setViewportSize(viewport);
    await terminal.locator('[data-enter-session]').click();
    await action('step').click();
    await action('return').click();
    await terminal.locator('[data-ask-status]').click();
    assert.ok(await input.isVisible());
    assert.equal(await terminal.evaluate(el => el.scrollWidth <= el.clientWidth + 1), true);
    await page.screenshot({ path: `output/playwright/terminal-recovery-${viewport.width}.png` });
  }
  assert.deepEqual(errors, []);
  outcomes.push('entry, trace actions, return and check-in remain reachable on mobile and short screens');
  const report = { url, passed: outcomes.length, outcomes, pageErrors: errors, limitations: ['A bounded execution model, not a BASIC interpreter or host operating-system terminal.', 'No human enjoyment or competitive originality claim; page reload resets recovery.'] };
  await writeFile('output/playwright/terminal-recovery-results.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} catch (error) { console.error(error); process.exitCode = 1; }
finally { await browser.close(); }
