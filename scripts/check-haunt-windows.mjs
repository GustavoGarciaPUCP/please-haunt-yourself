import { chromium } from "playwright";
import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
await mkdir("output/playwright", { recursive: true });
const browser = await chromium.launch({ channel: "chrome", headless: true });
const targetUrl = new URL("/haunt.html", process.env.HAUNT_BASE_URL ?? "http://127.0.0.1:5174").href;
const outcomes = [];
const errors = [];
const visible = async (page, id) => page.waitForFunction(id => {
 const el=document.getElementById(`window-${id}`);
 return el && !el.inert && getComputedStyle(el).display!=="none" && Number(getComputedStyle(el).opacity) > .999 && el.getAnimations().length===0;
}, id);
const inBounds = async page => {
 const boxes=await page.locator(".window:not([aria-hidden=true])").evaluateAll(elements => elements.map(el => {
  const r=el.getBoundingClientRect(); return {id:el.id,x:r.x,y:r.y,right:r.right,bottom:r.bottom,width:innerWidth,height:innerHeight,footer:document.getElementById("taskbar").getBoundingClientRect().top};
 }));
 for (const box of boxes) assert.ok(box.x>=0 && box.y>=0 && box.right<=box.width+1 && box.bottom<=box.footer+1, JSON.stringify(box));
};
try {
 const page=await browser.newPage({viewport:{width:1440,height:980},reducedMotion:"no-preference"});
 page.on("pageerror", error=>errors.push(error.message));
 await page.goto(targetUrl,{waitUntil:"networkidle"});
 await visible(page,"terminal");
 assert.ok(await page.locator("#window-terminal").evaluate(el => el.contains(document.activeElement)), "startup focuses an actual terminal control");
 await inBounds(page);
 outcomes.push("startup: terminal visible, focused and within desktop");
 await page.getByRole("button",{name:"Open ECHO",exact:true}).click();
 const openingTiming=await page.locator("#window-echo").evaluate(el=>el.getAnimations().map(a=>a.effect.getTiming().duration));
 assert.ok(openingTiming.includes(240),"opening actually uses the planned 240ms animation");
 await visible(page,"echo");
 await inBounds(page);
 await page.screenshot({path:"output/playwright/window-foundation-desktop.png"});
 outcomes.push("open: real 240ms transition settles without lingering animations");
 const race=await page.evaluate(()=>{
  const el=document.getElementById("window-echo");
  el.querySelector("[aria-label=Close]").click();
  const focusRestored=document.activeElement.id==="btn-echo";
  const inertImmediately=el.inert;
  document.getElementById("btn-echo").click();
  return {focusRestored,inertImmediately};
 });
 assert.deepEqual(race,{focusRestored:true,inertImmediately:true});
 await visible(page,"echo");
 await page.waitForTimeout(200);
 assert.equal(await page.locator("#window-echo").count(),1);
 await visible(page,"echo");
 outcomes.push("close/reopen: immediate focus/inert and latest request wins after old close deadline");
 const minimized=await page.evaluate(()=>{
  const el=document.getElementById("window-echo");
  el.dataset.instanceProbe="retained";
  el.querySelector("[aria-label=Minimize]").click();
  const result={focusRestored:document.activeElement.id==="btn-echo",inertImmediately:el.inert};
  document.getElementById("btn-echo").click();
  return result;
 });
 assert.deepEqual(minimized,{focusRestored:true,inertImmediately:true});
 await visible(page,"echo");
 assert.equal(await page.locator("#window-echo").getAttribute("data-instance-probe"),"retained");
 await page.waitForTimeout(200);
 await visible(page,"echo");
 outcomes.push("minimize/restore: same content instance survives interruption");
 await page.locator("#window-echo").getByRole("button",{name:"Close",exact:true}).click();
 await page.locator("#window-echo").waitFor({state:"detached"});
 await page.evaluate(()=>{document.getElementById("btn-echo").click();document.dispatchEvent(new KeyboardEvent("keydown",{key:"Escape",bubbles:true}));});
 await page.locator("#window-echo").waitFor({state:"detached"});
 assert.equal(await page.evaluate(()=>document.activeElement.id),"btn-echo");
 outcomes.push("Escape: closes during opening and restores taskbar focus");
 await page.locator("#btn-echo").click();
 await page.emulateMedia({reducedMotion:"reduce"});
 await visible(page,"echo");
 assert.equal(await page.locator("#window-echo").evaluate(el=>el.getAnimations().length),0);
 await page.locator("#window-echo").getByRole("button",{name:"Close",exact:true}).click();
 await page.locator("#window-echo").waitFor({state:"detached"});
 await page.locator("#btn-echo").focus();
 await page.keyboard.press("Enter");
 await visible(page,"echo");
 await page.keyboard.press("Escape");
 await page.locator("#window-echo").waitFor({state:"detached"});
 outcomes.push("reduced motion: active opening settles; keyboard reopen/close works");
 await page.locator("#btn-echo").click();
 await visible(page,"echo");
 await page.locator("#window-terminal [data-primary]").focus();
 const layers=await page.evaluate(()=>({terminal:Number(document.getElementById("window-terminal").style.zIndex),echo:Number(document.getElementById("window-echo").style.zIndex)}));
 assert.ok(layers.terminal>layers.echo,"keyboard focus brings the correct window forward");
 outcomes.push("keyboard focus: correct window raised without stale completion focus steal");
 await page.setViewportSize({width:390,height:844});
 await page.locator("#btn-echo").click();
 await visible(page,"echo");
 await inBounds(page);
 await page.screenshot({path:"output/playwright/window-foundation-mobile.png"});
 await page.setViewportSize({width:800,height:450});
 await inBounds(page);
 outcomes.push("layout: controls and windows remain in bounds at 390x844 and 800x450");
 assert.deepEqual(errors,[]);
 const report={url:targetUrl,passed:outcomes.length,outcomes,pageErrors:errors};
 await writeFile("output/playwright/window-foundation-results.json",JSON.stringify(report,null,2));
 console.log(JSON.stringify(report,null,2));
} catch (error) { console.error(error); process.exitCode=1; }
finally { await browser.close(); }
